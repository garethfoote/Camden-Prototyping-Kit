const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const { spawnSync } = require('node:child_process')
const core = require('../scripts/generate-content-spec')
const { invoke, extractScenarios, createSvg } = require('../scripts/lib/journey-export')
const router = require('../app/routes')
const scenarios = require('../scripts/export-scenarios/event-equipment')
const root = path.resolve(__dirname, '..')
const prefix = '/event-equipment/'
const extract = () => extractScenarios({ root, journey: 'event-equipment', scenarios, core })

test('all example pages, conditional states, labels and real error variants are exported', () => {
  const spec = extract()
  assert.equal(spec.pages.length, 12)
  assert.deepEqual(spec.warnings, [])
  const contact = spec.pages.find(p => p.route === prefix + 'contact')
  assert.equal(contact.variants.length, 1)
  assert.match(contact.bodyContent.join(' '), /ready to collect/)
  assert.match(contact.variants[0].bodyContent.join(' '), /arrange delivery/)
  const email = contact.questions.find(q => q.fieldName === 'equipmentEmail')
  assert.equal(email.conditionalParents[0].optionValue, 'Email')
  assert.deepEqual(email.validationMessages.sort(), ['Enter your email address', 'Enter an email address in the correct format'].sort())
  assert(spec.edges.some(e => e.from.endsWith('/eligibility') && e.to.endsWith('/not-eligible')))
  assert(spec.edges.some(e => e.from.endsWith('/equipment') && e.to.endsWith('/gazebo-location')))
  assert(spec.edges.some(e => e.from.endsWith('/gazebo-location') && e.to.endsWith('/park-permission')))
  const location = spec.pages.find(p => p.route.endsWith('/gazebo-location'))
  assert.equal(location.variants.length, 0)
})

test('branch changes clear obsolete answers and hidden fields are not required', () => {
  const result = invoke(router, 'POST', prefix + 'fulfilment', { equipmentAddress: 'Old address' }, { equipmentFulfilment: 'Collection' })
  assert.equal(result.data.equipmentAddress, undefined)
  assert.equal(result.redirect, prefix + 'collection')
  const contact = invoke(router, 'POST', prefix + 'contact', { equipmentEmail: 'old@example.test' }, { equipmentContact: 'Phone', equipmentPhone: '020 7946 0000' })
  assert.equal(contact.data.equipmentEmail, '')
  assert.equal(contact.redirect, prefix + 'equipment')
  const failure = invoke(router, 'POST', prefix + 'contact', {}, { equipmentContact: 'Email', equipmentEmail: 'wrong' })
  assert.equal(failure.status, 422)
  const html = core.createNunjucksEnvironment(root).render(failure.template + '.njk', failure.locals)
  assert.match(html, /href="#equipmentEmail"/)
  assert.match(html, /id="equipmentEmail-error"/)
  assert.match(html, /value="wrong"/)
})

test('equipment selection clears obsolete gazebo answers and protects its branches', () => {
  const changed = invoke(router, 'POST', prefix + 'equipment', { gazeboLocation: 'Camden park' }, { equipment: 'Tables' })
  assert.equal(changed.data.gazeboLocation, undefined)
  assert.equal(changed.redirect, prefix + 'check-answers')
  const location = invoke(router, 'POST', prefix + 'gazebo-location', { equipment: 'Gazebo' }, {})
  assert.equal(location.status, 422)
  const guarded = invoke(router, 'GET', prefix + 'park-permission', { equipment: 'Gazebo', gazeboLocation: 'Other outdoor space' })
  assert.equal(guarded.redirect, prefix + 'equipment')
})

test('missing page scenarios and unexpected transitions are detected', () => {
  const missing = extractScenarios({ root, journey: 'event-equipment', scenarios: scenarios.filter(s => !s.path.endsWith('/confirmation')), core })
  assert(missing.warnings.some(w => w.includes('confirmation')))
  assert.throws(() => extractScenarios({ root, journey: 'event-equipment', core, scenarios: [{ path: prefix + 'eligibility', submissions: [{ body: { equipmentEligible: 'No' }, expected: prefix + 'fulfilment' }] }] }), /expected/)
})

test('SVG escapes content and shared output files have matching revision and coverage', () => {
  const spec = extract()
  const svg = createSvg({ ...spec, journeyName: 'A < B & C', revisionLabel: 'r001', generatedAt: 'test' })
  assert.match(svg, /A &lt; B &amp; C/)
  assert.match(svg, /viewBox=/)
  assert(!svg.includes('<script'))
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'journey-export-'))
  const run = spawnSync(process.execPath, ['scripts/generate-content-spec.js', '--journey', 'event-equipment', '--strict', '--format', 'both', '--output', dir], { cwd: root, encoding: 'utf8' })
  assert.equal(run.status, 0, run.stderr)
  const files = fs.readdirSync(dir)
  assert.equal(files.length, 4)
  assert.deepEqual(files.map(f => path.extname(f)).sort(), ['.csv', '.json', '.md', '.svg'])
  assert.equal(new Set(files.map(f => f.slice(0, f.lastIndexOf('.')))).size, 1)
  const markdown = fs.readFileSync(path.join(dir, files.find(f => f.endsWith('.md'))), 'utf8')
  assert.match(markdown, /Verified validation cases/)
  assert.match(markdown, /Delivery — different introductory copy/)
  assert.match(markdown, /### Page content/)
  assert.match(markdown, /Text: We will contact you when your equipment is ready to collect\.\n\n2\. \*\*Type:\*\* Form component/)
  assert.match(markdown, /Email\n       - Reveals:\n         - \*\*Email address\*\*/)
  assert.doesNotMatch(markdown, /### Body content|### Questions and conditional content|Also exercised:|State: All relevant branches enabled/)
  assert.doesNotMatch(markdown, /#### \d+\./)
})

test('older permit and complaints exports still run, with honest static coverage warnings', () => {
  for (const journey of ['permit', 'complaints']) {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'journey-regression-'))
    const run = spawnSync(process.execPath, ['scripts/generate-content-spec.js', '--journey', journey, '--output', dir], { cwd: root, encoding: 'utf8' })
    assert.equal(run.status, 0, run.stderr)
    const spec = JSON.parse(fs.readFileSync(path.join(dir, fs.readdirSync(dir).find(f => f.endsWith('.json')))))
    assert(spec.pages.length >= 4)
    assert(spec.warnings.some(w => w.includes('No export scenarios')))
  }
})
